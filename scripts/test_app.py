def swipe(page, dx, y=320):
    page.mouse.move(195, y)
    page.mouse.down()
    steps = 10
    for i in range(1, steps + 1):
        page.mouse.move(195 + dx * i / steps, y, steps=2)
        page.wait_for_timeout(16)
    page.mouse.up()

